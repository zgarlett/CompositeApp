CREATE TABLE BILLING_ACCOUNTS (
  ACCOUNT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  ACCOUNT_NUMBER VARCHAR2(40 CHAR) NOT NULL,
  ACCOUNT_NAME VARCHAR2(160 CHAR) NOT NULL,
  BILLING_CONTACT VARCHAR2(160 CHAR) NOT NULL,
  BILLING_EMAIL VARCHAR2(254 CHAR) NOT NULL,
  BILLING_PHONE VARCHAR2(40 CHAR) NOT NULL,
  BILLING_ADDRESS VARCHAR2(500 CHAR) NOT NULL,
  PAYMENT_TERMS VARCHAR2(80 CHAR) NOT NULL,
  STATUS VARCHAR2(20 CHAR) DEFAULT 'Active' NOT NULL,
  CONSTRAINT BILLING_ACCOUNTS_PK PRIMARY KEY (ACCOUNT_ID),
  CONSTRAINT BILLING_ACCOUNTS_NUMBER_UQ UNIQUE (ACCOUNT_NUMBER),
  CONSTRAINT BILLING_ACCOUNTS_STATUS_CK
    CHECK (STATUS IN ('Active', 'Pending', 'On hold', 'Closed'))
);